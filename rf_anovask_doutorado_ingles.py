def registrar_impacto(
    nome_parametro,
    lista_valores,
    matriz_rmse,
    matriz_mae,
    matriz_r2,
    matriz_ttreino,
    matriz_tpred,
):
  """Calculates global statistics and selects the best RMSE value per quartile."""
  medias_rmse = np.mean(matriz_rmse, axis=1)
  medias_mae = np.mean(matriz_mae, axis=1)
  medias_r2 = np.mean(matriz_r2, axis=1)
  medias_ttreino = np.mean(matriz_ttreino, axis=1)
  medias_tpred = np.mean(matriz_tpred, axis=1)

  # Selection of the lowest RMSE for each of the 4 interval quartiles
  indices_quartis = np.array_split(range(len(lista_valores)), 4)
  melhores_4_quartis = []

  for indices in indices_quartis:
    if len(indices) > 0:
      rmse_quartil = medias_rmse[indices]
      idx_local = np.argmin(rmse_quartil)
      idx_global = indices[idx_local]
      melhores_4_quartis.append(lista_valores[idx_global])

  # Saves global statistics for the dynamic transition to Part 2
  impacto_hiperparametros[nome_parametro] = {
      'diff_rmse': np.max(medias_rmse) - np.min(medias_rmse),
      'melhor_valor_rmse': lista_valores[np.argmin(medias_rmse)],
      'diff_mae': np.max(medias_mae) - np.min(medias_mae),
      'melhor_valor_mae': lista_valores[np.argmin(medias_mae)],
      'diff_r2': np.max(medias_r2) - np.min(medias_r2),
      'melhor_valor_r2': lista_valores[np.argmax(medias_r2)],
      'diff_ttreino': np.max(medias_ttreino) - np.min(medias_ttreino),
      'melhor_valor_ttreino': lista_valores[np.argmin(medias_ttreino)],
      'diff_tpred': np.max(medias_tpred) - np.min(medias_tpred),
      'melhor_valor_tpred': lista_valores[np.argmin(medias_tpred)],
      'melhores_4_quartis': melhores_4_quartis,
  }

  # Saves the summary of best/worst RMSE for CSV export
  idx_melhor_rmse = np.argmin(medias_rmse)
  idx_pior_rmse = np.argmax(medias_rmse)
  resumo_parte1.append({
      'Hyperparameter': nome_parametro,
      'Best Value': lista_valores[idx_melhor_rmse],
      'Best RMSE': medias_rmse[idx_melhor_rmse],
      'Worst Value': lista_valores[idx_pior_rmse],
      'Worst RMSE': medias_rmse[idx_pior_rmse],
      'RMSE Difference (Worst - Best)': (
          medias_rmse[idx_pior_rmse] - medias_rmse[idx_melhor_rmse]
      ),
  })

